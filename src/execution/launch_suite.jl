module Launch

export launchPerfTestSuite

using ..PerfTest
using MacroTools
using TOML

DEFAULT_INTERPRETER_FLAGS = Dict{String,String}(
    "--check-bounds" => "no",
    "--project" => "."
)

# Name of the flag a token of the interpreter flags is, e.g. "--project" for "--project=." or "-O3" for "-O3"
flagName(token::AbstractString) = first(split(token, '='; limit=2))

"""
Arguments of the interpreter given by `flagstring` (e.g. "-O3 --depwarn=yes -L setup.jl"), split at whitespace, in the
order they are given: a flag whose value is a separate token (e.g. `-L setup.jl`) keeps it right after it, and a flag
given several times is passed each time (the interpreter decides, e.g. the last one for --depwarn). They are preceded by
the `default` flags that they do not set, e.g. --project=. unless they give --project.
"""
function parseFlags(flagstring::AbstractString, default::Dict{String,String})::Vector{String}
    given = String.(split(flagstring))
    given_names = Set(flagName.(given))
    # Sorted, so the command is the same every time
    defaults = ["$key=$value" for (key, value) in sort!(collect(default)) if !(key in given_names)]
    return vcat(defaults, given)
end

# Whether a token of the interpreter flags sets the number of threads: -t, -tN, --threads or --threads=N
isThreadsFlag(token::AbstractString) = (startswith(token, "-t") && !startswith(token, "--")) || flagName(token) == "--threads"


"""
Thread setting (general.numas, general.threads_per_numa) of a generated suite, `nothing` for a key no configuration call sets.
A suite has a single thread setting regardless of recursivity: each key takes its value from the last configuration call
of the suite that sets it, even when that call comes from an included recipe. The first call of the suite holds the whole
configuration it was generated with. An interpolated value is only known once the suite executes, it is not considered.
"""
function retrieveConfigThreadSpecs(suite::Expr)
    specs = Dict{String,Any}("numas" => nothing, "threads_per_numa" => nothing)
    MacroTools.prewalk(suite) do x
        if @capture(x, PerfTest._perftest_config(serializedconfig_))
            try
                general = get(TOML.parse(PerfTest.interpolationPreview(serializedconfig)), "general", Dict())
                for key in keys(specs)
                    if haskey(general, key) && !PerfTest.isInterpolated(general[key])
                        specs[key] = general[key]
                    end
                end
            catch e
                @error("Generated suite configuration is malformed TOML error: $e")
            end
        end
        return x
    end
    return specs["numas"], specs["threads_per_numa"]
end

"""
Arrangement (see Topology.ArrangementSpec) the generated suite at `path` is launched with, before it is resolved on this
machine. A @perftest_threads of the recipe takes priority. Otherwise it is given by the thread setting of the suite
(see retrieveConfigThreadSpecs and Topology.arrangementFromConfig), which the transform has already checked. An invalid
one, e.g. in a suite edited or generated by a different version of the package, throws an error naming the reason and
what the setting can be, as the suite cannot be launched with it.
"""
function suiteArrangement(path::AbstractString)
    return first(suiteArrangementOrigin(path))
end

"""
The arrangement of the generated suite at `path` (see suiteArrangement), along with where it comes from, how to change
it and what it can be, as named in the errors of the launcher.
"""
function suiteArrangementOrigin(path::AbstractString)::Tuple{Any,String,String,String}
    suite = PerfTest.loadFileAsExpr(path)

    # Extract the thread specifications of a @perftest_threads, see parseThreadsMacro
    specs = nothing
    stop = false
    MacroTools.prewalk((x -> @capture(x, specs = thr_) ? (specs = thr; stop = true; nothing) : (stop ? nothing : x)), suite)
    if specs !== nothing
        arrangement = eval(specs)
        return arrangement, "the @perftest_threads $(repr(arrangement)) of the recipe",
               "change the @perftest_threads of the recipe, or remove it to use the thread setting of the configuration " *
               "(general.numas and general.threads_per_numa)", PerfTest.THREADS_OPTIONS
    end

    # One thread setting per suite, a key no configuration call sets, only in a suite generated by an old version of the
    # package, has its default value
    numas, threads_per_numa = (something(spec, PerfTest.Configuration.DEFAULT["general"][key])
                               for (spec, key) in zip(retrieveConfigThreadSpecs(suite), PerfTest.THREAD_KEYS))
    arrangement = PerfTest.Topology.arrangementFromConfig(numas, threads_per_numa)
    if arrangement isa Vector{String}
        error("Cannot launch the suite $path, the thread setting of the generated suite is invalid, general.numas = " *
              "$(repr(numas)) and general.threads_per_numa = $(repr(threads_per_numa)): $(join(arrangement, ", ")). " *
              "$(PerfTest.Topology.THREAD_SETTING_RULE) $(PerfTest.Topology.CONFIG_THREADS_OPTIONS)")
    end
    return arrangement, "the thread setting of the suite, general.numas = $(repr(numas)) and general.threads_per_numa = " *
                        "$(repr(threads_per_numa))",
           "set general.numas and general.threads_per_numa (in the configuration file $(PerfTest.Configuration.CONFIG_FILE), " *
           "with the config argument of runperftests or with a @perftest_config of the recipe), or give the recipe a " *
           "@perftest_threads, which takes priority over them", PerfTest.Topology.CONFIG_THREADS_OPTIONS
end

"""
Arrangement the generated suite at `path` is launched with (see suiteArrangement), resolved on this machine (see
Topology.literallizeArrangement), e.g. (#numas, #threads_per_numa). It only sets the number of threads of the process
that executes the suite, the thread setting of the configuration does not pin threads, a @perftest_threads does.
"""
function retrieveThreadConfig(path::AbstractString)
    return literalArrangement(path, suiteArrangement(path))
end

function literalArrangement(path::AbstractString, arrangement)
    return try
        PerfTest.Topology.literallizeArrangement(arrangement)
    catch e
        e isa ErrorException || rethrow()
        error("Cannot launch the suite $path with the thread arrangement $(repr(arrangement)) on this machine: $(e.msg)")
    end
end

"""
Command that executes the generated suite at `path` in a new julia process, with the number of threads its thread
arrangement needs (see retrieveThreadConfig) and the given flags. `interpreter_flags` are passed to the interpreter (see
parseFlags), they cannot set the number of threads, it comes from the thread arrangement of the suite. `suite_flags` is
passed to the suite as a single argument, an empty one (or only whitespace) passes nothing.
"""
function suiteCommand(path::AbstractString, interpreter_flags::AbstractString="", suite_flags::AbstractString="")::Cmd
    # Retrieve current interpreter
    exename = joinpath(Sys.BINDIR, Base.julia_exename())
    # Convert to absolute path
    _abspath = abspath(path)
    # Check flags
    flags = parseFlags(interpreter_flags, DEFAULT_INTERPRETER_FLAGS)
    # Check thread configurations
    arrangement, origin, change, options = suiteArrangementOrigin(path)
    configurations = literalArrangement(path, arrangement)
    threads_needed = configurations[1] * configurations[2]
    # Add thread argument
    given = findfirst(isThreadsFlag, flags)
    if given !== nothing
        # With its value, when it is a separate token
        flag = flags[given] in ("-t", "--threads") && given < length(flags) ? join(flags[given:given+1], " ") : flags[given]
        error("Cannot launch the suite $path with the interpreter flag `$flag` of interpreter_flags: the launcher sets " *
              "the number of threads of the process that executes the suite, from the thread arrangement of the suite, " *
              "to $threads_needed (--threads=$threads_needed), given by $origin, which is $(repr(configurations)) " *
              "(#numas, #threads_per_numa) on this machine. Remove `$flag` from interpreter_flags. To change the number " *
              "of threads, $change, then generate the suite again (runperftests does). $options")
    end
    args = isempty(strip(suite_flags)) ? String[] : [suite_flags]
    return `$exename $flags --threads=$threads_needed $_abspath $args`
end

"""
    Runs the julia interpreter to execute a performance test suite, setting up adequately (e.g. thread number, flags)
"""
function launchPerfTestSuite(path::AbstractString, interpreter_flags::AbstractString="", suite_flags::AbstractString="")
    # Spawn process
    run(suiteCommand(path, interpreter_flags, suite_flags))
end

end